"""Export verified heading passages from completed, rendered public guides."""

from hashlib import sha256
from html import escape
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import shutil
import sys
import xml.etree.ElementTree as ET

ORIGIN = "https://docs.kanrimemberships.com"
VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source", "track", "wbr"}
BLOCK = {"p", "li", "tr", "div", "aside", "blockquote", "pre", "br", "td", "th"}


class Node:
    def __init__(self, tag="", attrs=None):
        self.tag, self.attrs, self.children = tag, dict(attrs or []), []

    def text(self):
        if self.tag in {"script", "style", "svg"} or self.attrs.get("aria-hidden") == "true":
            return ""
        if {"sr-only", "sl-anchor-link"}.intersection(self.attrs.get("class", "").split()):
            return ""
        body = "".join(child if isinstance(child, str) else child.text() for child in self.children)
        return f"\n{body}\n" if self.tag in BLOCK else body

    def nodes(self):
        yield self
        for child in self.children:
            if isinstance(child, Node):
                yield from child.nodes()


class Document(HTMLParser):
    def __init__(self, html):
        super().__init__(convert_charrefs=True)
        self.root = Node()
        self.stack = [self.root]
        self.feed(html)
        self.close()

    def handle_starttag(self, tag, attrs):
        node = Node(tag, attrs)
        self.stack[-1].children.append(node)
        if tag not in VOID:
            self.stack.append(node)

    def handle_endtag(self, tag):
        for index in range(len(self.stack) - 1, 0, -1):
            if self.stack[index].tag == tag:
                del self.stack[index:]
                return

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in VOID:
            self.handle_endtag(tag)

    def handle_data(self, text):
        self.stack[-1].children.append(text)


def clean(text):
    return "\n".join(line.strip() for line in text.splitlines() if line.strip())


def sections(html):
    nodes = list(Document(html).root.nodes())
    articles = [node for node in nodes if "sl-markdown-content" in node.attrs.get("class", "").split()]
    titles = [node.text().strip() for node in nodes if node.tag == "h1"]
    if len(articles) != 1 or len(titles) != 1:
        raise ValueError("Expected one rendered article and page heading")
    result, parts, heading, anchor = [], [], None, None

    def flush():
        text = clean("".join(parts))
        if text:
            result.append({"section": heading, "anchor": anchor, "text": text})
        parts.clear()

    def walk(node):
        nonlocal heading, anchor
        if node.tag in {"h2", "h3", "h4", "h5", "h6"}:
            flush()
            heading, anchor = clean(node.text()), node.attrs.get("id")
            if not heading or not anchor or not re.fullmatch(r"[a-z0-9][a-z0-9-]*", anchor):
                raise ValueError(f"Unverified heading anchor: {anchor}")
        elif not any(child.tag.startswith("h") and child.tag[1:].isdigit()
                     for child in node.nodes() if child is not node):
            parts.append(node.text())
        else:
            for child in node.children:
                if isinstance(child, Node):
                    walk(child)
                else:
                    parts.append(child)

    walk(articles[0])
    flush()
    return titles[0], result


def split_text(text, limit=1900):
    while len(text) > limit:
        end = text.rfind("\n", 0, limit + 1)
        if end < limit // 2:
            end = text.rfind(" ", 0, limit + 1)
        if end < 1:
            end = limit
        yield text[:end].strip()
        text = text[end:].strip()
    if text:
        yield text


def build(directory):
    sitemap = ET.fromstring((directory / "kai-sitemap.xml").read_text())
    ns = {"s": "http://www.sitemaps.org/schemas/sitemap/0.9"}
    entries = sitemap.findall("s:url", ns)
    aliases = json.loads((Path(__file__).parent / "search-aliases.json").read_text())
    output = directory / "kai-passages"
    if output.exists():
        # This directory is exclusively generated by this exporter.
        shutil.rmtree(output)
    passages = []
    seen_aliases = set()
    for entry in entries:
        url = entry.findtext("s:loc", namespaces=ns)
        if not url.startswith(ORIGIN + "/") or not url.endswith("/"):
            raise ValueError("Invalid approved guide URL")
        path = url[len(ORIGIN):]
        title, chunks = sections((directory / path.lstrip("/") / "index.html").read_text())
        for section in chunks:
            key = path + ("#" + section["anchor"] if section["anchor"] else "")
            terms = aliases.get(key, [])
            if terms:
                seen_aliases.add(key)
            for part, excerpt in enumerate(split_text(section["text"])):
                # Stable identity preserves index continuity across text edits.
                identity = sha256(f"{url}#{section['anchor'] or ''}:{part}".encode()).hexdigest()[:32]
                source_url = f"{ORIGIN}/kai-passages/{identity}/"
                passage = {
                    "source_url": source_url, "url": url, "doc_title": title,
                    "section": section["section"], "anchor": section["anchor"],
                    "excerpt": excerpt, "aliases": terms,
                }
                passages.append(passage)
                target = directory / "kai-passages" / identity / "index.html"
                target.parent.mkdir(parents=True, exist_ok=True)
                body = f"{title}\n{section['section'] or ''}\n{excerpt}"
                target.write_text(
                    '<!doctype html><html lang="en"><head><meta charset="utf-8">'
                    '<meta name="googlebot" content="noindex">'
                    '<meta name="bingbot" content="noindex"><title>' + escape(title) +
                    '</title></head><body><main class="kai-passage"><pre>' + escape(body) +
                    '</pre><p>Search terms: ' + escape(", ".join(terms)) +
                    '</p></main></body></html>'
                )
    if set(aliases) != seen_aliases:
        raise ValueError(f"Search aliases reference missing headings: {set(aliases) - seen_aliases}")
    if not 1 <= len(passages) <= 10000 or len({p["source_url"] for p in passages}) != len(passages):
        raise ValueError("Invalid passage count or duplicate identity")
    modified = max(entry.findtext("s:lastmod", namespaces=ns) for entry in entries)
    manifest = json.dumps({"version": 1, "built_at": modified, "passages": passages}, ensure_ascii=False)
    if len(manifest.encode()) > 8 * 1024 * 1024:
        raise ValueError("Passage manifest exceeds 8 MiB")
    (directory / "kai-passages.json").write_text(manifest)
    urls = "\n".join(f"<url><loc>{p['source_url']}</loc><lastmod>{modified}</lastmod></url>" for p in passages)
    (directory / "kai-search-sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' + urls + "</urlset>"
    )
    print(f"Exported {len(passages)} heading passages from {len(entries)} guides ({len(manifest.encode())} bytes).")


if __name__ == "__main__":
    build(Path(sys.argv[1] if len(sys.argv) > 1 else "dist"))
